def output(base, profile):
    if profile not in PROFILES:
        raise ValueError(f"Unknown kernel profile: {profile}")
    base = Path(base)
    return base if profile == "stable" else base / profile


def requirements(required, disabled, profile):
    """Return exact resolved Kconfig expectations, not best-effort requests."""
    output("/out", profile)
    if profile == "stable":
        return set(required), set(), set(disabled)
    import hardware_profile
    modules = set(MODULES) | set(hardware_profile.MODULES)
    builtin = (set(required) | set(BUILTIN) | set(hardware_profile.BUILTIN)) - modules
    off = (set(disabled) - builtin - modules) | set(DISABLED)
    if builtin & off or modules & off or builtin & modules:
        raise ValueError("Conflicting experimental kernel requirements")
    return builtin, modules, off
