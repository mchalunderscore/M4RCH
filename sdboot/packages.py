"""Build local pacman packages from verified kernel outputs and explicit policy.

makepkg runs unprivileged in the disposable Arch root. The generated recipes,
source tarballs and provenance are published alongside the packages so the
binary-input packaging step can be inspected and repeated independently.
"""
